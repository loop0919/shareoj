import { expect, test } from '@playwright/test'
import { shortId } from '../shared/utils/short-id'

for (const width of [320, 375, 414, 768, 1280]) {
  test(`creation dropdown fits ${width}px when open`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto('/')
    await page.locator('.create-menu summary').click()
    const menu = page.locator('.create-menu-links')
    await expect(menu).toBeVisible()
    const bounds = (await menu.boundingBox())!
    expect(bounds.x).toBeGreaterThanOrEqual(0)
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
  })
}

test('creation dropdown supports keyboard, dismissal, and creation links', async ({ page }) => {
  await page.goto('/')
  const nav = page.getByRole('navigation', { name: 'メインナビゲーション' })
  const toggle = nav.locator('summary')
  const problem = nav.getByRole('link', { name: '新規問題' })
  const blog = nav.getByRole('link', { name: '新規記事' })
  await expect(problem).toBeHidden()
  await toggle.focus()
  await page.keyboard.press('Enter')
  await expect(problem).toBeVisible()
  await expect(problem).toHaveAttribute('href', '/problems/new?fresh=1')
  await expect(blog).toHaveAttribute('href', '/blog/new')
  await page.keyboard.press('Escape')
  await expect(problem).toBeHidden()
  await expect(toggle).toBeFocused()
  await toggle.click()
  await page.locator('h1').click()
  await expect(problem).toBeHidden()
  await page.setViewportSize({ width: 375, height: 812 })
  await toggle.click()
  await expect(blog).toBeInViewport()
  await expect(problem).toBeInViewport()
  await blog.click()
  await expect(page).toHaveURL(/\/blog\/new$/)
})

test('contest pages replace the site menu with the contest menu', async ({ page }) => {
  const contest = `/contests/${shortId('88888888-8888-4888-8888-888888888888')}`
  const siteMenu = page.getByRole('navigation', { name: 'メインナビゲーション' })
  const contestMenu = page.getByRole('navigation', { name: 'コンテストメニュー' })
  await page.goto(`${contest}?view=standings`)
  await expect(siteMenu).toHaveCount(0)
  const header = page.locator('.site-header')
  await expect(header.getByRole('link', { name: '共有コンテスト', exact: true })).toHaveAttribute('href', contest)
  await expect(header).toContainText('開催中2026/09/10 9:00 〜 11:00')
  // Only the overview repeats the contest title, authors and schedule in the page body.
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('公式順位表')
  await expect(page.getByText('開始日時', { exact: true })).toHaveCount(0)
  const breadcrumb = page.getByRole('navigation', { name: 'パンくずリスト' })
  await expect(breadcrumb).toHaveText('共有コンテスト/順位表')
  await expect(breadcrumb.getByRole('link', { name: '共有コンテスト', exact: true })).toHaveAttribute('href', contest)
  await expect(contestMenu.getByRole('link')).toHaveText(['概要', '問題', '順位表', '提出一覧', '解説一覧', '質問・回答'])
  await expect(contestMenu.getByRole('link', { name: '順位表', exact: true })).toHaveAttribute('aria-current', 'page')
  await contestMenu.getByRole('link', { name: '問題', exact: true }).click()
  await expect(page).toHaveURL(`${contest}?view=problems`)
  await expect(contestMenu.getByRole('link', { name: '問題', exact: true })).toHaveAttribute('aria-current', 'page')
  await expect(contestMenu.getByRole('link', { name: '順位表', exact: true })).not.toHaveAttribute('aria-current')
  await contestMenu.getByRole('link', { name: '概要', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('共有コンテスト')
  await expect(page.getByText('開始日時', { exact: true })).toBeVisible()
  await expect(page.getByText('日時はJSTで表示しています。', { exact: true })).toBeVisible()
  await expect(breadcrumb).toHaveText('コンテスト/共有コンテスト')
  await contestMenu.getByRole('link', { name: '問題', exact: true }).click()
  await page.getByRole('region', { name: 'コンテストの問題' }).getByRole('link').first().click()
  await expect(page).toHaveURL(`${contest}/A`)
  await expect(contestMenu.getByRole('link', { name: '問題', exact: true })).toHaveAttribute('aria-current', 'true')
  await expect(breadcrumb.getByRole('link')).toHaveText(['共有コンテスト', '問題'])
  // The problem's own tabs come after its title so the two menus do not stack.
  const problemMenu = page.getByRole('navigation', { name: '問題メニュー' })
  await expect(problemMenu.getByRole('link', { name: '問題文', exact: true })).toHaveAttribute('aria-current', 'page')
  expect(await page.locator('.problem-header, .problem-menu').evaluateAll(nodes => nodes.map(node => node.className))).toEqual(['problem-header', 'problem-menu'])
  await page.goto(`${contest}/submissions/22222222-2222-4222-8222-222222222222`)
  await expect(contestMenu.getByRole('link', { name: '提出一覧', exact: true })).toHaveAttribute('aria-current', 'true')
  await expect(header).toContainText('共有コンテスト')
  for (const width of [320, 375, 768]) {
    await page.setViewportSize({ width, height: 900 })
    await expect(contestMenu.getByRole('link', { name: '解説一覧', exact: true })).toBeInViewport()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.getByRole('link', { name: 'ShareOJ ホーム' }).click()
  await expect(siteMenu).toBeVisible()
  await expect(contestMenu).toHaveCount(0)
  await expect(header).not.toContainText('共有コンテスト')
  await page.goto('/contests/00000000-0000-4000-8000-000000000000')
  await expect(siteMenu).toBeVisible()
})

test('contest pages keep a clock for the start, the end, and the time after it', async ({ page }) => {
  const clock = page.locator('.contest-clock')
  await page.clock.setFixedTime(new Date('2026-09-07T22:58:57Z'))
  await page.goto('/contests/88888888-8888-4888-8888-888888888888?view=standings')
  await expect(clock).toHaveText('開始まで2日 1:01:03')
  await page.clock.setFixedTime(new Date('2026-09-09T23:00:00Z'))
  await expect(clock).toHaveText('開始まで1:00:00')
  await page.clock.setFixedTime(new Date('2026-09-10T01:30:00Z'))
  await expect(clock).toHaveText('終了まで0:30:00')
  await page.clock.setFixedTime(new Date('2026-09-10T03:04:05Z'))
  await expect(clock).toHaveText('2026/09/10（木）12:04:05')
  await page.clock.setFixedTime(new Date('2026-09-11T00:04:05Z'))
  await expect(clock).toHaveText('2026/09/11（金）09:04:05')
  for (const width of [320, 1280]) {
    await page.setViewportSize({ width, height: 700 })
    const bounds = (await clock.boundingBox())!
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
    expect(bounds.x + bounds.width).toBeGreaterThan(width - 40)
    expect(bounds.y + bounds.height).toBeGreaterThan(700 - 40)
  }
  await clock.click()
  await expect(clock).toHaveCSS('opacity', '0.1')
  await clock.click()
  await expect(clock).toHaveCSS('opacity', '1')
  // Scrolling to the end leaves the footer clear of the clock.
  await page.evaluate(() => window.scrollTo(0, document.documentElement.scrollHeight))
  const footer = (await page.locator('.site-footer').boundingBox())!
  expect(footer.y + footer.height).toBeLessThanOrEqual((await clock.boundingBox())!.y)
  await page.getByRole('link', { name: 'ShareOJ ホーム' }).click()
  await expect(page.getByRole('navigation', { name: 'メインナビゲーション' })).toBeVisible()
  await expect(clock).toHaveCount(0)
})
