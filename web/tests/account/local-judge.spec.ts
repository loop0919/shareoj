import { expect, test } from '@playwright/test'

test('local Docker generates persistent inputs and outputs and scores the generated tests', async ({ page }) => {
  test.skip(!process.env.BROWSER_JUDGE_IMAGE, 'requires the local Docker judge')
  test.setTimeout(120000)
  await page.goto('/login')
  await page.getByLabel('メールアドレス').fill('test_cases@example.test')
  await page.getByLabel('パスワード', { exact: true }).fill('test-password')
  await page.getByRole('button', { name: 'ログイン', exact: true }).click()
  await expect(page).toHaveURL('/my')
  page.on('dialog', dialog => dialog.accept())
  await page.goto('/problems/new')
  await page.getByLabel('問題のタイトル').fill('Local generation and scoring')
  await page.getByRole('button', { name: 'テストケース', exact: true }).click()
  await page.getByRole('button', { name: '生成・検証・判定', exact: true }).click()
  await page.locator('.generator-options select').selectOption('python314')
  await page.getByLabel('入力生成のコード', { exact: true }).fill("print('x'*70000)")
  await page.getByRole('button', { name: '生成する', exact: true }).click()
  await expect(page.getByText('1件の入力を追加しました。')).toBeVisible({ timeout: 30000 })
  await page.getByRole('button', { name: '出力生成', exact: true }).click()
  await page.locator('.generator-options select').selectOption('python314')
  await page.getByLabel('出力生成のコード', { exact: true }).fill('print(len(input()))')
  await page.getByRole('button', { name: '生成する', exact: true }).click()
  await expect(page.getByText('1件の出力を更新しました。')).toBeVisible({ timeout: 30000 })
  const id = new URL(page.url()).searchParams.get('problem')!
  await expect(page.locator('.draft-status').getByRole('status')).toHaveText('保存済み')
  await page.reload()
  await page.getByRole('button', { name: 'テストケース', exact: true }).click()
  await expect(page.getByLabel('出力', { exact: true })).toContainText('70000')
  const headers = { origin: 'http://127.0.0.1:13002' }
  const problem = await (await page.request.get(`/api/my/problems/${id}`)).json()
  expect(problem.draft.testCases[0].inputFile.size).toBe(70001)
  problem.draft.scoring = { mode: 'groups', groups: [{ name: 'large', points: 100 }] }
  problem.draft.testCases[0].groups = ['large']
  const saved = await page.request.put(`/api/my/problems/${id}`, { headers, data: { version: problem.version, draft: problem.draft } })
  expect(saved.status()).toBe(200)
  const created = await page.request.post('/api/my/submissions', { headers, data: { problemId: id, runtime: 'python314', source: 'print(len(input()))' } })
  expect(created.status()).toBe(202)
  const submission = await created.json()
  await expect.poll(async () => (await (await page.request.get(`/api/my/submissions/${submission.id}`)).json()).status, { timeout: 30000 }).toBe('DONE')
  const finished = await (await page.request.get(`/api/my/submissions/${submission.id}`)).json()
  expect(finished.result.verdict).toBe('AC')
  expect(finished.result.scoring.score).toBe(10000)
})
